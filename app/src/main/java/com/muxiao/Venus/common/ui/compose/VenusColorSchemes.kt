    /** 按主题偏好下标与深浅色取 ColorScheme（非 Composable 纯函数，任意线程可调）。 */
    @JvmStatic
    fun forIndex(context: Context, index: Int, dark: Boolean): ColorScheme = when (index) {
        in 1..6 -> if (dark) FIXED_DARK.getValue(index) else FIXED_LIGHT.getValue(index)
        else -> dynamicScheme(context, dark)
    }

    /** Java 侧取色辅助：底色 role 的 ColorInt（背景合成 / 窗口背景注入用）。 */
    @JvmStatic
    fun surfaceArgb(context: Context, index: Int, dark: Boolean): Int =
        forIndex(context, index, dark).surface.toArgb()

    /** Java 侧取色辅助：background role 的 ColorInt（窗口背景注入用）。 */
    @JvmStatic
    fun backgroundArgb(context: Context, index: Int, dark: Boolean): Int =
        forIndex(context, index, dark).background.toArgb()

